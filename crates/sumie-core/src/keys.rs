/// A press, its repeats and its release share this identity even if the layout changes.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum PhysicalKey {
    Code(KeyCode),
    /// Opaque adapter identity. Two unrecognized keys may be held at once.
    Unidentified(u32),
}

impl PhysicalKey {
    /// Encoder key ID (zero for an unidentified position).
    #[must_use]
    pub fn ghostty_key(self) -> u8 {
        match self {
            Self::Code(code) => code as u8,
            Self::Unidentified(_) => 0,
        }
    }
}

